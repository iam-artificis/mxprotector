; =============================================================================
; entry.asm
; [STUB] PIC точка входа STUB runtime (x64, MASM).
;
; Последовательность:
;   1. Выделение 8-байтного placeholder'а на стеке (для OEP)
;   2. Сохранение ВСЕХ регистров (GPR + RFLAGS + XMM0-XMM15)
;   3. Выравнивание стека + Shadow Space (x64 ABI)
;   4. Вызов stub_main() -> возвращает VA OEP в RAX
;   5. Запись OEP в placeholder
;   6. Восстановление ВСЕХ регистров (100%, включая RAX и R15)
;   7. Переход на OEP через RET (стековый трамплин)
;
; Паттерн "Stack Placeholder + RET Trick":
;   В начале выделяем 8 байт на стеке. После stub_main записываем OEP
;   в эту ячейку. При восстановлении всех регистров RSP оказывается ровно
;   на placeholder'е. Инструкция RET снимает OEP со стека, прыгает на него
;   и оставляет RSP в идеальном состоянии (RSP = X, как при входе).
;
; Математика стека (X = RSP при входе):
;   sub rsp, 8            -> RSP = X - 0x08   (placeholder)
;   16 push (GPR+RFLAGS)  -> RSP = X - 0x88   (16*8 = 0x80)
;   sub rsp, 100h         -> RSP = X - 0x188  (XMM save area)
;   ...stub_main...
;   mov [rsp+180h], rax   -> пишет в (X-0x188)+0x180 = X-0x08 (placeholder!)
;   add rsp, 100h         -> RSP = X - 0x88
;   16 pop                -> RSP = X - 0x08
;   ret                   -> pop RIP = OEP, RSP = X
; =============================================================================

.code

EXTERN stub_main:PROC

; =============================================================================
; stub_entry — точка входа STUB (заменяет OEP в защищённом PE)
; =============================================================================
stub_entry PROC

    ; -----------------------------------------------------------------
    ; 0. Placeholder для OEP (8 байт)
    ;    Резервируем слот на стеке. Позже сюда запишем адрес OEP.
    ;    Инструкция RET в конце снимет его и передаст управление.
    ; -----------------------------------------------------------------
    sub     rsp, 8

    ; -----------------------------------------------------------------
    ; 1. Сохранение всех GPR + RFLAGS (16 pushes = 128 байт = 0x80)
    ; -----------------------------------------------------------------
    push    rax
    push    rcx
    push    rdx
    push    rbx
    push    rbp
    push    rsi
    push    rdi
    push    r8
    push    r9
    push    r10
    push    r11
    push    r12
    push    r13
    push    r14
    push    r15
    pushfq

    ; -----------------------------------------------------------------
    ; 2. Сохранение XMM регистров (16 * 16 = 256 байт = 0x100)
    ; -----------------------------------------------------------------
    sub     rsp, 100h

    movdqu  [rsp + 000h], xmm0
    movdqu  [rsp + 010h], xmm1
    movdqu  [rsp + 020h], xmm2
    movdqu  [rsp + 030h], xmm3
    movdqu  [rsp + 040h], xmm4
    movdqu  [rsp + 050h], xmm5
    movdqu  [rsp + 060h], xmm6
    movdqu  [rsp + 070h], xmm7
    movdqu  [rsp + 080h], xmm8
    movdqu  [rsp + 090h], xmm9
    movdqu  [rsp + 0A0h], xmm10
    movdqu  [rsp + 0B0h], xmm11
    movdqu  [rsp + 0C0h], xmm12
    movdqu  [rsp + 0D0h], xmm13
    movdqu  [rsp + 0E0h], xmm14
    movdqu  [rsp + 0F0h], xmm15

    ; -----------------------------------------------------------------
    ; 3. Выравнивание стека и вызов stub_main (Microsoft x64 ABI)
    ;
    ;    RBP фиксирует текущий RSP до выравнивания — гарантированная
    ;    точка восстановления после возврата из stub_main.
    ; -----------------------------------------------------------------
    mov     rbp, rsp
    and     rsp, 0FFFFFFFFFFFFFFF0h
    sub     rsp, 20h                ; Shadow space (32 байта)

    call    stub_main               ; RAX = VA OEP (или 0 при ошибке)

    ; -----------------------------------------------------------------
    ; 4. Восстановление стека и запись OEP в placeholder
    ; -----------------------------------------------------------------
    mov     rsp, rbp                ; Откат к моменту до выравнивания

    ; Смещение до placeholder'а от текущего RSP:
    ;   XMM area = 0x100, GPR area = 0x80 -> 0x100 + 0x80 = 0x180
    mov     [rsp + 180h], rax

    ; -----------------------------------------------------------------
    ; 5. Восстановление XMM регистров
    ; -----------------------------------------------------------------
    movdqu  xmm0,  [rsp + 000h]
    movdqu  xmm1,  [rsp + 010h]
    movdqu  xmm2,  [rsp + 020h]
    movdqu  xmm3,  [rsp + 030h]
    movdqu  xmm4,  [rsp + 040h]
    movdqu  xmm5,  [rsp + 050h]
    movdqu  xmm6,  [rsp + 060h]
    movdqu  xmm7,  [rsp + 070h]
    movdqu  xmm8,  [rsp + 080h]
    movdqu  xmm9,  [rsp + 090h]
    movdqu  xmm10, [rsp + 0A0h]
    movdqu  xmm11, [rsp + 0B0h]
    movdqu  xmm12, [rsp + 0C0h]
    movdqu  xmm13, [rsp + 0D0h]
    movdqu  xmm14, [rsp + 0E0h]
    movdqu  xmm15, [rsp + 0F0h]

    add     rsp, 100h               ; Освобождаем XMM area

    ; -----------------------------------------------------------------
    ; 6. Восстановление ВСЕХ GPR + RFLAGS (100%)
    ; -----------------------------------------------------------------
    popfq
    pop     r15
    pop     r14
    pop     r13
    pop     r12
    pop     r11
    pop     r10
    pop     r9
    pop     r8
    pop     rdi
    pop     rsi
    pop     rbp
    pop     rbx
    pop     rdx
    pop     rcx
    pop     rax

    ; -----------------------------------------------------------------
    ; 7. Переход на OEP через RET (стековый трамплин)
    ;
    ;    RSP указывает ровно на placeholder (X - 8), куда мы на шаге 4
    ;    записали адрес OEP. Инструкция RET:
    ;      - снимает 8 байт (OEP) со стека в RIP
    ;      - делает RSP = RSP + 8 = X (исходное состояние)
    ;    Все регистры оригинальные, стек чист — OEP получает управление
    ;    в том же состоянии, в котором его ожидает OS Loader.
    ; -----------------------------------------------------------------
    ret

stub_entry ENDP

END
